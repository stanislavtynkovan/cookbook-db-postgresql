-- 7. Плоская таблица для BI: одна строка = одно блюдо
CREATE OR REPLACE VIEW v_dishes_overview AS
SELECT
    d.dish_id,
    d.dish_name,
    c.category_name,
    p.category_name                                  AS parent_category,
    (EXTRACT(EPOCH FROM d.total_time) / 60)::int     AS cooking_minutes,
    COUNT(DISTINCT di.ingredient_id)                 AS ingredients_count,
    COUNT(DISTINCT dt.technique_id)                  AS techniques_count
FROM dishes d
JOIN dishcategories c        ON c.category_id = d.category_id
LEFT JOIN dishcategories p   ON p.category_id = c.parent_id
LEFT JOIN dishes_ingredients di ON di.dish_id = d.dish_id
LEFT JOIN dishes_techniques dt  ON dt.dish_id = d.dish_id
GROUP BY d.dish_id, d.dish_name, c.category_name, p.category_name, d.total_time;

-- 8. Проверка: сколько блюд в каждой категории и среднее время
SELECT category_name,
       COUNT(*)                        AS dishes,
       ROUND(AVG(cooking_minutes), 1)  AS avg_minutes
FROM v_dishes_overview
GROUP BY category_name
ORDER BY dishes DESC;
